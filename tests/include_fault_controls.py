FIXTURES = {
    "accepted_rejection": (FLAT_REJECTION, INCLUDE_REJECTION, CHILD_REJECTION, "control.reject"),
    "changed_collection_target": (FLAT_COLLECTION, INCLUDE_COLLECTION, CHILD_CREATE, "control.create"),
    "wrong_object_read": (FLAT_WRONG_OBJECT, INCLUDE_WRONG_OBJECT, CHILD_CREATE, "control.create"),
}


class ControlAuth(ports.Authenticator):
    def session(self, role):
        return {"role": role}


class ControlRecorder(ports.Recorder):
    def __init__(self):
        self.items = []

    def record(self, response):
        self.items.append(response)

    def responses(self):
        return list(self.items)


class ControlNormalizer(ports.ResponseNormalizer):
    def normalize(self, response):
        # Transport data only; this function never inspects the declaration.
        return ports.NormalizedResponse(
            response.json["ok"], copy.deepcopy(response.json["data"]), response.status, response)


class ControlApi(ports.ApiDriver):
    """Deterministic in-memory service with exactly three switchable faults."""

    def __init__(self, fault=None):
        self.fault = fault
        self.reached = 0
        self.sent = []
        self.observed = []
        self.record = None

    def send(self, spec, session):
        self.sent.append((spec.method, spec.path, copy.deepcopy(spec.body)))
        status, ok, data = 200, True, {}
        if spec.method == "POST" and spec.path == "records":
            if spec.body["name"] == "":
                status, ok = 422, False
                if self.fault == "accepted_rejection":
                    self.reached += 1
                    status, ok = 201, True
            else:
                self.record = {"id": "record-1", "name": spec.body["name"]}
                data, status = copy.deepcopy(self.record), 201
        elif spec.method == "GET" and spec.path == "records":
            data = {"records": [
                {"id": "unrelated", "name": "other-name"},
                *([copy.deepcopy(self.record)] if self.record else []),
            ]}
            if self.fault == "changed_collection_target" and self.record:
                self.reached += 1
                data["records"][1]["name"] = "changed-name"
        elif spec.method == "GET" and spec.path == "records/record-1" and self.record:
            data = copy.deepcopy(self.record)
            if self.fault == "wrong_object_read":
                self.reached += 1
                data["id"] = "record-2"
        else:
            raise AssertionError("Control received an unexpected request")
        self.observed.append({"status": status, "ok": ok, "data": copy.deepcopy(data)})
        return ports.RecordedResponse(status, {}, {"ok": ok, "data": data}, "", None, spec)


def write_control(directory, fault, form):
    flat, included, child, child_id = FIXTURES[fault]
    path = directory / "scenario.yaml"
    path.write_text(flat if form == "flat" else included, encoding="utf-8")
    if form == "include":
        child_bytes = child.encode("utf-8")
        (directory / "child.yaml").write_bytes(child_bytes)
        (directory / "scenario.includes.json").write_text(json.dumps({
            "manifest_version": 1,
            "scenarios": {child_id: {
                "path": "child.yaml", "sha256": hashlib.sha256(child_bytes).hexdigest(),
            }},
        }), encoding="utf-8")
    return path


def run_control(fault, form="flat", *, inject=True):
    api = ControlApi(fault if inject else None)
    adapters = Adapters(
        auth=ControlAuth(), api=api, state=None, ui=None,
        recorder_factory=ControlRecorder,
        resolve_request=lambda scenario, step, template: ports.RequestSpec(
            template.method, template.path, copy.deepcopy(template.body)),
        normalizer=ControlNormalizer(),
    )
    try:
        with tempfile.TemporaryDirectory(prefix="refract-include-control-") as directory:
            report = run_scenario(write_control(Path(directory), fault, form), adapters,
                                  projections=("backend",))
    except Exception as exc:
        return {"fault": fault, "form": form, "injected": inject,
                "classification": "invalid_control", "error_type": type(exc).__name__,
                "fault_reached": api.reached, "requests": api.sent}
    domain = report.domains[0]
    failures = [{"step": check.step.removeprefix("setup/"), "check": check.check}
                for check in domain.checks if not check.ok]
    statuses = [(step.step_id.removeprefix("setup/"), step.status) for step in domain.steps]
    expected_failure = {
        "accepted_rejection": {"step": "reject", "check": "failure"},
        "changed_collection_target": {"step": "list", "check": "collection_matching_count"},
        "wrong_object_read": {"step": "read", "check": "field_equals"},
    }[fault]
    valid = not any(status == "ERROR" for _, status in statuses)
    if inject:
        valid = valid and api.reached == 1
        detected = report.status == "FAILED" and failures == [expected_failure]
        outcome = "detected" if valid and detected else "missed" if valid else "invalid_control"
    else:
        outcome = "passing_neighbor" if valid and report.status == "PASSED" else "invalid_control"
    return {"fault": fault, "form": form, "injected": inject, "classification": outcome,
            "status": report.status, "fault_reached": api.reached,
            "failures": failures, "steps": statuses, "requests": api.sent,
            "observed": api.observed, "degradations": report.degradations()}


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--flat-only", action="store_true")
    args = parser.parse_args()
    forms = ("flat",) if args.flat_only else ("flat", "include")
    results = [run_control(fault, form, inject=inject)
               for form in forms for fault in FAULTS for inject in (False, True)]
    faults = [result for result in results if result["injected"]]
    executed = sum(result["classification"] in ("detected", "missed") for result in faults)
    detected = sum(result["classification"] == "detected" for result in faults)
    print(json.dumps({"results": results, "detected": detected, "valid_executed": executed,
                      "ratio": f"{detected}/{executed}" if executed else "N/A",
                      "exclusions": [r for r in faults if r["classification"] == "invalid_control"]},
                     indent=2))
    return 0 if all(result["classification"] in ("detected", "passing_neighbor")
                    for result in results) else 1


if __name__ == "__main__":
    raise SystemExit(main())
